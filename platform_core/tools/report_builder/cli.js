#!/usr/bin/env node
'use strict';

/**
 * Report Builder CLI — turns a report model (JSON) into the platform's standard
 * self-contained HTML report.
 *
 *   node cli.js build --model <model.json> --out <report.html>
 *   node cli.js validate --model <model.json>
 *   node cli.js schema
 *
 * The Markdown report stays the authoritative artifact; this produces the
 * shareable HTML view alongside it.
 */

const fs = require('fs');
const path = require('path');

const { ReportModelError, normalizeModel } = require('./model');
const { renderReport, verifyHtml } = require('./render');

const USAGE = `Usage:
  cli.js build    --model <model.json> [--out <report.html>] [--stdout]
  cli.js validate --model <model.json>
  cli.js verify   --model <model.json> [--html <report.html>]   the HTML is exactly what this model renders
  cli.js schema   [--json]

Options:
  --model <path>   Report model JSON. Use "-" to read from stdin.
  --out <path>     Where to write the HTML. Defaults next to the model file.
  --stdout         Write the HTML to stdout instead of a file.
  --json           Machine-readable output.
`;

function parseArgs(argv) {
  const args = { _: [], flags: {} };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith('--')) {
      args._.push(arg);
      continue;
    }
    const name = arg.slice(2);
    if (name === 'stdout' || name === 'json' || name === 'help') {
      args.flags[name] = true;
      continue;
    }
    const next = argv[i + 1];
    if (next === undefined || next.startsWith('--')) {
      throw new Error(`--${name} requires a value`);
    }
    args.flags[name] = next;
    i += 1;
  }
  return args;
}

function readStdin() {
  return fs.readFileSync(0, 'utf8');
}

function loadModel(modelPath) {
  if (!modelPath) throw new Error('--model is required');
  const raw = modelPath === '-' ? readStdin() : fs.readFileSync(path.resolve(modelPath), 'utf8');
  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error(`--model is not valid JSON: ${error.message}`);
  }
}

function defaultOutPath(modelPath) {
  const resolved = path.resolve(modelPath);
  const dir = path.dirname(resolved);
  const base = path.basename(resolved).replace(/\.report\.json$|\.json$/i, '');
  return path.join(dir, `${base}.html`);
}

/**
 * R-03 (Phase 9.5): a report is written only inside the platform data root — the configured one, or a
 * --data-root that is a data root (it holds runs/ and knowledge_base/) — or inside a root a named human
 * registered there as report-output (target_write/cli.js register-root --kind report-output).
 */
function assertReportDestination(outPath, dataRootFlag) {
  // eslint-disable-next-line global-require
  const { realPathOf } = require('../run_manager/pathBoundary');
  let dataRoot;
  if (typeof dataRootFlag === 'string') {
    dataRoot = path.resolve(dataRootFlag);
    if (!fs.existsSync(path.join(dataRoot, 'runs')) || !fs.existsSync(path.join(dataRoot, 'knowledge_base'))) throw new Error(`--data-root ${dataRoot} is not a platform data root (it needs runs/ and knowledge_base/).`);
  } else {
    // eslint-disable-next-line global-require
    dataRoot = require('../platform_paths/paths').resolveRoots({ startDir: process.cwd(), fresh: true }).dataRoot;
  }
  const norm = (p) => (process.platform === 'win32' ? p.toLowerCase() : p);
  const real = realPathOf(path.resolve(outPath));
  const rel = path.relative(norm(realPathOf(dataRoot)), norm(real));
  if (rel && !rel.startsWith('..') && !path.isAbsolute(rel)) return;
  // eslint-disable-next-line global-require
  const { permittedRootFor } = require('../run_manager/targetWrites');
  if (permittedRootFor(dataRoot, outPath, ['report-output'])) return;
  throw new Error(`${outPath} is outside the platform data root (${dataRoot}) and every registered report-output root — a report is written nowhere else (use --stdout to print it).`);
}

function commandBuild(args) {
  const model = loadModel(args.flags.model);
  const html = renderReport(model);

  if (args.flags.stdout) {
    process.stdout.write(html);
    return 0;
  }

  const outPath = args.flags.out
    ? path.resolve(args.flags.out)
    : defaultOutPath(args.flags.model === '-' ? 'report.json' : args.flags.model);

  // Fail closed (Phase 9.4): build writes a report and nothing else — an .html file, and never over a file this
  // builder did not generate (a stray --out must not overwrite source code or another project's files).
  if (!/\.html?$/i.test(outPath)) throw new Error(`--out must name an .html file (got ${outPath}) — the builder writes reports only.`);
  assertReportDestination(outPath, args.flags['data-root']);
  if (fs.existsSync(outPath)) {
    const head = fs.readFileSync(outPath, 'utf8').slice(0, 4096);
    if (!/<meta name="report-model-sha256" content="[0-9a-f]{64}">/.test(head)) throw new Error(`${outPath} exists and was not generated by report_builder — it is never overwritten.`);
  }
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, html, 'utf8');

  if (args.flags.json) {
    process.stdout.write(`${JSON.stringify({ ok: true, out: outPath, bytes: Buffer.byteLength(html) }, null, 2)}\n`);
  } else {
    process.stdout.write(`Wrote ${outPath} (${Buffer.byteLength(html)} bytes)\n`);
  }
  return 0;
}

/**
 * verify (Phase 9.3, F-28): the HTML next to a model is exactly what the model renders — for every pipeline
 * report, not only the Final QA Report. Exit 0 match · 3 mismatch or missing HTML · 2 invalid model.
 */
function commandVerify(args) {
  const model = loadModel(args.flags.model);
  normalizeModel(model);
  const htmlPath = args.flags.html ? path.resolve(args.flags.html) : defaultOutPath(args.flags.model);
  let html = null;
  try { html = fs.readFileSync(htmlPath, 'utf8'); } catch { /* missing */ }
  const r = html === null ? { ok: false, reason: 'the HTML is missing — build it from the model' } : verifyHtml(html, model);
  if (args.flags.json) process.stdout.write(`${JSON.stringify({ ok: r.ok, html: htmlPath, reason: r.reason }, null, 2)}\n`);
  else process.stdout.write(r.ok ? `OK — ${htmlPath} is exactly what the model renders\n` : `MISMATCH — ${htmlPath}: ${r.reason}\n`);
  return r.ok ? 0 : 3;
}

function commandValidate(args) {
  const model = loadModel(args.flags.model);
  const normalized = normalizeModel(model);

  const categories = normalized.testCases ? normalized.testCases.categories.length : 0;
  const cases = normalized.testCases
    ? normalized.testCases.categories.reduce((sum, c) => sum + c.cases.length, 0)
    : 0;
  const result = {
    ok: true,
    title: normalized.title,
    statuses: normalized.statuses.map((s) => s.key),
    categories,
    testCases: cases,
    sections: normalized.sections.map((s) => `${s.type}:${s.title}`),
  };

  if (args.flags.json) {
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  } else {
    process.stdout.write(
      `Model is valid — ${cases} test case(s) in ${categories} category/ies, `
      + `${normalized.sections.length} section(s).\n`,
    );
  }
  return 0;
}

function commandSchema(args) {
  const doc = path.join(__dirname, 'README.md');
  if (args.flags.json) {
    process.stdout.write(`${JSON.stringify({ ok: true, reference: doc }, null, 2)}\n`);
    return 0;
  }
  process.stdout.write(fs.readFileSync(doc, 'utf8'));
  return 0;
}

function main(argv) {
  let args;
  try {
    args = parseArgs(argv);
  } catch (error) {
    process.stderr.write(`${error.message}\n\n${USAGE}`);
    return 1;
  }

  const command = args._[0];
  if (!command || args.flags.help) {
    process.stdout.write(USAGE);
    return command ? 0 : 1;
  }

  try {
    if (command === 'build') return commandBuild(args);
    if (command === 'validate') return commandValidate(args);
    if (command === 'verify') return commandVerify(args);
    if (command === 'schema') return commandSchema(args);
    process.stderr.write(`Unknown command "${command}".\n\n${USAGE}`);
    return 1;
  } catch (error) {
    if (error instanceof ReportModelError) {
      // Exit 2 marks "the model is wrong", separate from an I/O or usage failure.
      process.stderr.write(`Invalid report model — ${error.message}\n`);
      return 2;
    }
    process.stderr.write(`${error.message}\n`);
    return 1;
  }
}

if (require.main === module) {
  process.exitCode = main(process.argv.slice(2));
}

module.exports = { main, parseArgs };
