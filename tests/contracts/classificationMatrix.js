// Drift classification accuracy matrix (Phase 7.1).
//
// Each case is one controlled change to a REAL specification — the Swagger Petstore OpenAPI 3.0.4
// document (fixtures/swagger-petstore/openapi.yaml, Apache-2.0) — with the classification it must get and
// WHY, written from the consumer-compatibility reasoning below, not read back from the tool's output:
//
//   A change is BREAKING when a consumer that worked against the old contract fails against the new one
//   with no change on its side: a request it sends is now refused, or a response it reads no longer has
//   the shape, type, value or status it relies on.
//   POTENTIALLY BREAKING when that failure depends on how the consumer is written (a closed switch over an
//   enum, error handling keyed on a status code, a field it may or may not read) — or when a test that
//   asserts the old value would now fail although a tolerant client would not.
//   NON-BREAKING when every existing consumer keeps working: additive, or relaxing what a client must send.
//   UNKNOWN when the comparison cannot see enough to decide (a construct it does not model, a schema in
//   another document, a composition whose members cannot be paired). Unknown is never treated as safe.
//
// Direction matters, because Pet (and Order, User) are both SENT (POST/PUT bodies) and RECEIVED (GET
// responses): requests are judged from the server's side of the bargain (what callers must send), responses
// from the reader's (what callers can rely on). Hence one change can be Breaking in one direction and
// Non-breaking in the other — the matrix checks both.
//
// `expect`: every entry must be present ({rule, classification, direction?, where?(item)}).
// `overall`: the comparison's overall classification. `absent`: rules that must NOT appear.

